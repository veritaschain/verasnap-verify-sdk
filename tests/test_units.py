TSA = Path(__file__).parent / "fixtures" / "tsa"
DATA = (TSA / "data.bin").read_bytes()
IMPRINT = hashlib.sha256(DATA).digest()


# ---------------------------------------------------------------- RFC 3161 (real tokens, 2026-11-18)


@pytest.mark.parametrize("name", ["digicert", "aimoda", "sectigo", "apple", "globalsign"])
def test_real_tokens_verify(name):
    res = check_timestamp_token((TSA / f"{name}.tsr").read_bytes(), expected_imprint=IMPRINT, trust=TrustStore.default())
    assert res.outcome == "verified", res.reason
    assert res.verified_gen_time is not None and res.gen_time.year == 2026


def test_token_wrong_imprint_is_invalid():
    res = check_timestamp_token((TSA / "digicert.tsr").read_bytes(), expected_imprint=b"\x00" * 32, trust=TrustStore.default())
    assert res.outcome == "invalid" and res.verified_gen_time is None
    assert res.message_imprint == IMPRINT  # still reported for diagnostics


def test_token_untrusted_root():
    store = TrustStore([a for a in TrustStore.default().anchors if "Sectigo" in a.subject.rfc4514_string()])
    res = check_timestamp_token((TSA / "digicert.tsr").read_bytes(), expected_imprint=IMPRINT, trust=store)
    assert res.outcome == "untrusted_chain" and res.verified_gen_time is None


def test_token_tampered_tstinfo_is_invalid():
    tok = bytearray((TSA / "digicert.tsr").read_bytes())
    i = tok.find(IMPRINT)
    tok[i + 40] ^= 0x01  # inside TSTInfo, after the imprint (serial / genTime)
    res = check_timestamp_token(bytes(tok), expected_imprint=IMPRINT, trust=TrustStore.default())
    assert res.outcome == "invalid"


def test_token_garbage():
    assert check_timestamp_token(b"\x30\x03\x02\x01\x00", expected_imprint=None, trust=TrustStore.default()).outcome == "invalid"
    assert check_timestamp_token(b"not der", expected_imprint=None, trust=TrustStore.default()).outcome == "invalid"


def test_no_trust_store_never_verifies():
    res = check_timestamp_token((TSA / "digicert.tsr").read_bytes(), expected_imprint=IMPRINT, trust=None)
    assert res.outcome == "untrusted_chain"


