# ---------------------------------------------------------------- Merkle


@pytest.mark.parametrize("n", list(range(1, 34)))
def test_merkle_build_and_verify(n):
    hashes_ = ["sha256:" + hashlib.sha256(bytes([i])).hexdigest() for i in range(n)]
    tree = merkle.build(hashes_)
    for i, h in enumerate(hashes_):
        if n == 1:
            assert merkle.verify_single(h, tree.root) == (True, False)
        else:
            assert merkle.verify_inclusion(h, tree.proofs[i], i, tree.root)
            assert not merkle.verify_inclusion("sha256:" + "00" * 32, tree.proofs[i], i, tree.root)


def test_merkle_legacy_single_root():
    h = "sha256:" + "ab" * 32
    assert merkle.verify_single(h, "ab" * 32) == (True, True)


# ---------------------------------------------------------------- iOS model projection


def test_projection_drops_unknown_and_nulls():
    event = {
        "EventID": "e", "ChainID": "c", "PrevHash": "GENESIS", "Timestamp": "t", "EventType": "INGEST", "HashAlgo": "SHA256",
        "SignAlgo": "ES256", "EventHash": "h", "Signature": "s",
        "Asset": {"AssetID": "a", "AssetType": "IMAGE", "AssetHash": "x", "AssetName": "n", "AssetSize": 1, "MimeType": "m", "VideoMetadata": None},
        "CaptureContext": {"DeviceID": "d", "DeviceModel": "m", "OSVersion": "o", "AppVersion": "v", "CaptureAssertion": {"KeyID": "k"}},
    }
    out, dropped = project(event)
    assert "VideoMetadata" not in out["Asset"]
    assert dropped == ["CaptureContext.CaptureAssertion"]


# ---------------------------------------------------------------- input robustness


def test_rejects_non_proof_json():
    v = Verifier()
    assert v.verify(b"{}").status.value == "ERROR"
    assert v.verify(b"[1,2]").status.value == "ERROR"
    assert v.verify(b"not json").status.value == "ERROR"
    assert v.verify(b'{"a": NaN}').status.value == "ERROR"


def test_evidence_pack_without_proof():
    import io
    import zipfile

    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as zf:
        zf.writestr("media.jpg", b"x")
    from verasnap_verify import ProofFormatError

    with pytest.raises(ProofFormatError):
        Verifier().verify(buf.getvalue())


